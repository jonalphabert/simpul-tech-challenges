-- Delivery Planning: database schema (PostgreSQL)
-- Based on idea.md, section 1.

DROP TABLE IF EXISTS order_plan_detail;
DROP TABLE IF EXISTS order_plan;
DROP TABLE IF EXISTS order_detail;
DROP TABLE IF EXISTS "order";
DROP TABLE IF EXISTS warehouse_stock;
DROP TABLE IF EXISTS warehouse;
DROP TABLE IF EXISTS product;

CREATE TABLE product (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL UNIQUE,
    category          VARCHAR(50)  NOT NULL,
    need_refrigerator BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Distance lives here because there is only one client.
-- Each warehouse has exactly one van, described by delivery_fleet.
CREATE TABLE warehouse (
    id                             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                           VARCHAR(10)  NOT NULL UNIQUE,
    location                       VARCHAR(100) NOT NULL,
    distance                       INTEGER      NOT NULL CHECK (distance >= 0), -- km to the client
    refrigerated_storage_available BOOLEAN      NOT NULL DEFAULT FALSE,
    delivery_fleet                 VARCHAR(20)  NOT NULL
        CHECK (delivery_fleet IN ('standard', 'refrigerated'))
);

CREATE TABLE warehouse_stock (
    id_warehouse INTEGER NOT NULL REFERENCES warehouse (id) ON DELETE CASCADE,
    id_product   INTEGER NOT NULL REFERENCES product (id)   ON DELETE CASCADE,
    quantity     INTEGER NOT NULL CHECK (quantity >= 0),
    PRIMARY KEY (id_warehouse, id_product)
);

-- "order" is a reserved word, so it must stay quoted.
CREATE TABLE "order" (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE order_detail (
    id_order   INTEGER NOT NULL REFERENCES "order" (id) ON DELETE CASCADE,
    id_product INTEGER NOT NULL REFERENCES product (id),
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (id_order, id_product)
);

-- One order can have one ranked set of plans per objective.
CREATE TABLE order_plan (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_order     INTEGER     NOT NULL REFERENCES "order" (id) ON DELETE CASCADE,
    objective    VARCHAR(20) NOT NULL
        CHECK (objective IN ('min_max_distance', 'min_vans')),
    rank         INTEGER     NOT NULL CHECK (rank >= 1),
    max_distance INTEGER,
    vans_used    INTEGER,
    status       VARCHAR(20) NOT NULL
        CHECK (status IN ('feasible', 'infeasible')),
    UNIQUE (id_order, objective, rank)
);

-- The warehouse also identifies the van (one van per warehouse).
CREATE TABLE order_plan_detail (
    id_order_plan INTEGER NOT NULL REFERENCES order_plan (id) ON DELETE CASCADE,
    id_warehouse  INTEGER NOT NULL REFERENCES warehouse (id),
    id_product    INTEGER NOT NULL REFERENCES product (id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (id_order_plan, id_warehouse, id_product)
);
